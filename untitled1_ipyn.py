# Plot 2: Skill Clusters Distribution
plt.figure(figsize=(8, 8))
skill_clusters_data = {k: v for k, v in skill_clusters_data.items() if v > 0}
plt.pie(skill_clusters_data.values(), labels=skill_clusters_data.keys(), autopct='%1.1f%%')
plt.title('Skill Clusters Distribution')
plt.show()

# Plot 3: Salary Distribution
plt.figure(figsize=(10, 6))
metrics = ['Average', '25th %ile', 'Median', '75th %ile']
values = [salary_stats_data['average'], salary_stats_data['percentile_25'],
         salary_stats_data['median'], salary_stats_data['percentile_75']]
plt.bar(metrics, values, color=colors[2])
plt.title('Salary Distribution')
plt.ylabel('Salary ($)')
plt.xticks(rotation=45)
plt.show()

# Plot 4: Job Locations
plt.figure(figsize=(8, 8))
locations, counts = zip(*locations_data)
