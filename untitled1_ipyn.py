# Plot 8: Top Skill Gaps to Address
plt.figure(figsize=(10, 6))
if skill_gaps_data:
    plt.barh(skill_gaps_data, range(1, len(skill_gaps_data) + 1), color=colors[7])
    plt.xlabel('Priority Level')
    plt.title('Top Skill Gaps to Address')
    plt.gca().invert_yaxis()
