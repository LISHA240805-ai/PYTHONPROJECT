# Plot 10: Career Progression Path
plt.figure(figsize=(10, 6))
if career_progression_data:
    steps = [f"Step {p['step']}" for p in career_progression_data]
    plt.plot(steps, range(len(steps)), marker='o', color=colors[9])
    plt.ylabel('Progression Level')
    plt.title('Career Progression Path')
    plt.xticks(rotation=45)
