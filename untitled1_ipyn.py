    steps = [f"Step {step['step']}" for step in learning_path_data]
    durations = [step['duration_weeks'] for step in learning_path_data]
    plt.bar(steps, durations, color=colors[8])
    plt.ylabel('Weeks')
    plt.title('Learning Path Timeline')
